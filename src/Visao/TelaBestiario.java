    private void aplicarFiltros() {
        c.filtrarInimigos(
            jTextFieldBestiario,
            jCheckBoxLagartos,   // cbLagartos
            jCheckBoxArtropodes, // cbArtropodes
            jCheckBoxPlantas,    // cbPlantas
            jCheckBoxOutros,     // cbOutros
            jCheckBoxEspecial,   // cbEspeciais
            jCheckBoxPacifico,   // cbPacificos
            jCheckBoxHostil,     // cbHostis
            jCheckBoxAgressivo
        );

// 1. Carrega a imagem original do seu pacote
ImageIcon referencia = new ImageIcon(getClass().getResource("/Recursos/bestiario/Green_Lizard_icon.png"));

int largura = 80;
int altura = 80;

// 2. Redimensiona a imagem (CORRIGIDO: mudou para Image e Image.SCALE_SMOOTH)
Image imagemRedimensionada = referencia.getImage().getScaledInstance(
    largura, 
    altura, 
    Image.SCALE_SMOOTH
);

// 3. Aplica a nova imagem redimensionada de volta no JLabel
jLabelIcone1.setIcon(new ImageIcon(imagemRedimensionada));
}

