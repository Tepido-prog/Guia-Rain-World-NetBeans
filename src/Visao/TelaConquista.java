/**
     * MÉTODO AUXILIAR: Lê o estado dos filtros do topo e pede para o controlador popular a tela.
     */
    private void carregarTelaComFiltros() {
        ControladorConquista controlador = new ControladorConquista();
        
        // Pega se os filtros de "Apenas passagens" ou "Apenas conquistas" estão marcados
        boolean ocultarPassagens = FiltroPassagem.isSelected();
        boolean ocultarConquistas = FiltroConquista.isSelected();
        
        // Chama o controlador passando todos os componentes e os estados dos filtros
        controlador.carregarConquistasNoPainel(jPanelConquistaEsquerda,       // O painel da esquerda (onde entram os checkboxes dinâmicos)
            ProgressoConquista,            // A barra de progresso
            IconeConquista,                // O JLabel do símbolo da conquista
            IconePassagem,                 // O JLabel da arte grande da passagem
            jTextAreaRequisitoConquista,   // O JTextArea de requisitos e descrição
            jLabelConclusaoConquista,      // O JLabel separado para a descrição
            jLabelNomeConquista,           // O JLabel para o nome
            jLabelTipoConquista,           // O JLabel para o tipo
            jLabelDescricaoConquista,               // O JLabel com o texto "CONCLUÍDO!"
            ocultarPassagens,              // Filtro
            ocultarConquistas              // Filtro
        );
    }
